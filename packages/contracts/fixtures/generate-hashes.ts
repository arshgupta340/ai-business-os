// Computes every stored hash for the fixtures and writes hashes.generated.ts.
// Run from the repo root: npx tsx packages/contracts/fixtures/generate-hashes.ts
// Node script, not part of the fixture exports.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { cartHash, idempotencyKey, payloadHash, type ApprovalPayload } from '../src/index';
import { approvals } from './approvals';
import { executions } from './executions';
import { orders } from './orders';

async function main(): Promise<void> {
  const out: Record<string, string> = {};
  const cartByOrder = new Map<string, string>();

  for (const o of orders) {
    const h = await cartHash(o.cart);
    cartByOrder.set(o.id, h);
    out[`cart:${o.id}`] = h;
  }

  // Order payloads carry the cart hash, which may still be the placeholder on a first run: use the fresh one.
  for (const a of approvals) {
    let payload: ApprovalPayload = a.payload;
    if (a.bundleType === 'order_bundle') payload = { ...a.payload, cartHash: cartByOrder.get(a.subjectId) ?? a.payload.cartHash };
    out[`payload:${a.id}`] = await payloadHash(payload);
  }

  for (const e of executions) {
    const approval = approvals.find((a) => a.id === e.approvalId);
    if (approval === undefined) throw new Error(`no approval ${e.approvalId}`);
    out[`idem:${e.id}`] = await idempotencyKey({ businessId: e.businessId, subjectId: approval.subjectId, actionType: e.actionType, approvalId: approval.id });
  }

  const lines = Object.keys(out)
    .sort()
    .map((k) => `  '${k}': '${out[k]}',`);
  const text = `// GENERATED by fixtures/generate-hashes.ts. Do not edit by hand.\nexport const GENERATED_HASHES: Record<string, string> = {\n${lines.join('\n')}\n};\n`;
  const target = fileURLToPath(new URL('./hashes.generated.ts', import.meta.url));
  writeFileSync(target, text);
  console.log(`wrote ${lines.length} hashes to ${target}`);
}

await main();
